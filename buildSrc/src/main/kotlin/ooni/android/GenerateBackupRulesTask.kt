package ooni.android

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

/**
 * Generates the Android backup rule resources (`xml/backup_rules.xml` for Android 11 and
 * lower, `xml/data_extraction_rules.xml` for Android 12+) for the selected organization.
 *
 * AndroidSecureStorage encrypts values with a key that lives in the Android Keystore.
 * Keystore keys are never backed up, so restoring the encrypted prefs file on a new install
 * or device leaves ciphertext that can no longer be decrypted (AEADBadTagException). The
 * rules keep `<baseSoftwareName>_secure_prefs.xml` out of cloud backups and device transfers.
 *
 * Android reads these rules from the APK, so they must exist as resources at build time.
 */
abstract class GenerateBackupRulesTask : DefaultTask() {
    @get:Input
    abstract val baseSoftwareName: Property<String>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val securePrefsFile = "${baseSoftwareName.get()}_secure_prefs.xml"
        val exclude = """<exclude domain="sharedpref" path="$securePrefsFile" />"""
        val xmlDir = outputDir.get().asFile.resolve("xml")
        xmlDir.deleteRecursively()
        xmlDir.mkdirs()

        xmlDir.resolve("backup_rules.xml").writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by GenerateBackupRulesTask. Do not edit. -->
            |<full-backup-content>
            |    $exclude
            |</full-backup-content>
            |
            """.trimMargin(),
        )

        xmlDir.resolve("data_extraction_rules.xml").writeText(
            """
            |<?xml version="1.0" encoding="utf-8"?>
            |<!-- Generated by GenerateBackupRulesTask. Do not edit. -->
            |<data-extraction-rules>
            |    <cloud-backup>
            |        $exclude
            |    </cloud-backup>
            |    <device-transfer>
            |        $exclude
            |    </device-transfer>
            |</data-extraction-rules>
            |
            """.trimMargin(),
        )
    }
}
